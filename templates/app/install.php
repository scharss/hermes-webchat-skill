    <?php endif; ?>
  <?php else: ?>
    <p>Step <?= $step ?> of 2 - <?= $step === 1 ? 'Database' : 'Administrator' ?></p>

    <?php foreach ($errors as $error): ?>
      <div class="error"><?= installer_h($error) ?></div>
    <?php endforeach; ?>

    <?php if ($missing): ?>
      <div class="error">Missing PHP extensions: <?= installer_h(implode(', ', $missing)) ?></div>
    <?php endif; ?>

    <?php if ($step === 1): ?>
