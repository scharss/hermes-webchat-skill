<?php
declare(strict_types=1);

require __DIR__ . '/inc/env.php';

if (session_status() !== PHP_SESSION_ACTIVE) {
    session_name('webchat_install');
    session_start();
}

$root = __DIR__;
$envFile = $root . '/.env';
$installed = is_file($envFile);

$required = ['pdo_mysql', 'mbstring', 'json', 'session', 'fileinfo'];
$missing = array_values(array_filter($required, static fn (string $ext): bool => !extension_loaded($ext)));

if (empty($_SESSION['install_csrf'])) {
    $_SESSION['install_csrf'] = bin2hex(random_bytes(32));
}
$csrf = $_SESSION['install_csrf'];

$errors = [];
$step = isset($_GET['step']) && $_GET['step'] === '2' ? 2 : 1;
$db = $_SESSION['install_db'] ?? [
    'host' => '127.0.0.1',
    'port' => '3306',
    'name' => 'hermes_webchat',
    'user' => '',
    'pass' => '',
];

function installer_h(?string $value): string
{
    return htmlspecialchars((string) $value, ENT_QUOTES, 'UTF-8');
}

function installer_db(array $db): PDO
{
    $dsn = sprintf('mysql:host=%s;port=%s;dbname=%s;charset=utf8mb4', $db['host'], $db['port'], $db['name']);
    return new PDO($dsn, $db['user'], $db['pass'], [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    ]);
}

if (!$installed && $_SERVER['REQUEST_METHOD'] === 'POST') {
    if (!hash_equals($csrf, (string) ($_POST['_csrf'] ?? ''))) {
        $errors[] = 'The form expired. Reload the page.';
    } else {
        $action = $_POST['action'] ?? '';

        if ($action === 'database') {
            $db = [
                'host' => trim($_POST['db_host'] ?? '127.0.0.1'),
                'port' => trim($_POST['db_port'] ?? '3306'),
                'name' => trim($_POST['db_name'] ?? ''),
                'user' => trim($_POST['db_user'] ?? ''),
                'pass' => (string) ($_POST['db_pass'] ?? ''),
            ];
            if ($db['name'] === '' || $db['user'] === '') {
                $errors[] = 'Database name and user are required.';
            } else {
                try {
                    installer_db($db)->query('SELECT 1');
                    $_SESSION['install_db'] = $db;
                    header('Location: install.php?step=2');
                    exit;
                } catch (Throwable $error) {
                    $errors[] = 'Cannot connect: ' . $error->getMessage();
                }
            }
        }

        if ($action === 'admin') {
            $db = $_SESSION['install_db'] ?? $db;
            $appName = trim($_POST['app_name'] ?? 'Hermes Webchat');
            $username = trim($_POST['username'] ?? '');
            $email = trim($_POST['email'] ?? '');
            $password = (string) ($_POST['password'] ?? '');
            $publicUrl = trim($_POST['public_url'] ?? '');

            if ($appName === '' || $username === '' || $email === '') {
                $errors[] = 'App name, username and email are required.';
            }
            if (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
                $errors[] = 'Enter a valid email address.';
            }
            if (strlen($password) < 8) {
                $errors[] = 'The password needs at least 8 characters.';
            }
            if (!$db) {
                $errors[] = 'The database step was not completed.';
            }

            if (!$errors) {
                try {
                    $pdo = installer_db($db);
                    $schema = (string) file_get_contents($root . '/schema.sql');
                    $schema = preg_replace('/^--.*$/m', '', $schema) ?? '';
                    foreach (preg_split('/;\s*\n/', $schema) ?: [] as $statement) {
                        $statement = trim($statement);
                        if ($statement !== '') {
                            $pdo->exec($statement);
                        }
                    }

                    $stmt = $pdo->prepare(
                        'INSERT INTO users (username, email, password_hash, role, quota)
                         VALUES (?, ?, ?, "admin", NULL)
                         ON DUPLICATE KEY UPDATE password_hash = VALUES(password_hash), role = "admin", active = 1'
                    );
                    $stmt->execute([$username, $email, password_hash($password, PASSWORD_DEFAULT)]);

                    foreach (['sessions', 'attachments', 'uploads'] as $folder) {
                        $dir = $root . '/storage/' . $folder;
                        if (!is_dir($dir)) {
                            mkdir($dir, 0770, true);
                        }
                    }

                    $installId = bin2hex(random_bytes(8));
                    $lines = [
                        '# Hermes Webchat - generated by install.php',
                        'WEBCHAT_INSTALL_ID=' . $installId,
                        'WEBCHAT_APP_NAME="' . str_replace('"', '', $appName) . '"',
                        'WEBCHAT_PUBLIC_URL="' . str_replace('"', '', $publicUrl) . '"',
                        'WEBCHAT_SESSION_HOURS=8',
                        'WEBCHAT_MAX_UPLOAD_MB=25',
                        'WEBCHAT_MAX_MESSAGE_CHARS=8000',
                        'WEBCHAT_DEFAULT_QUOTA=',
                        'WEBCHAT_APPROVAL_SECONDS=280',
                        '',
                        'DB_HOST=' . $db['host'],
                        'DB_PORT=' . $db['port'],
                        'DB_NAME=' . $db['name'],
                        'DB_USER=' . $db['user'],
                        'DB_PASS=' . $db['pass'],
                        '',
                    ];
                    if (file_put_contents($envFile, implode("\n", $lines)) === false) {
                        $errors[] = 'Cannot write .env. Check folder permissions.';
                    } else {
                        @chmod($envFile, 0640);
                        unset($_SESSION['install_db']);
                        header('Location: install.php?done=1');
                        exit;
                    }
                } catch (Throwable $error) {
                    $errors[] = 'Installation failed: ' . $error->getMessage();
                }
            }
        }
    }
}
